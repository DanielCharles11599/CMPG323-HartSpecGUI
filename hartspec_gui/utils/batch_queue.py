# batch_queue.py — FR-21: validated observation-block queue, review gates and JSON persistence.
"""Pure-Python batch manifest operations; never execute science or write to the FITS archive.

Batch input is the *committed* Page 01 source handoff. File_check has already
supplied ``observation_blocks`` (block-file name -> ordered FITS basenames).
Ambiguous/missing/quarantined/corrupt inputs remain visible as INVALID jobs;
we never guess which spectrum should be used or silently drop a block.

Manifests live at <SESSIONS_PATH>/batches/<batch-id>.json. They are distinct
from FR-19's immutable manual session saves and its checkpoint streams.
Batch execution is activated only after a compatible, frozen reference-session
template has been pinned. The worker handles science outside this persistence layer.
"""

from __future__ import annotations

import copy
import json
import math
import os
import re
import tempfile
import threading
import uuid
from collections import Counter
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Mapping, Sequence

MAX_MANIFEST_BYTES = 4 * 1024 * 1024
QUEUE_VERSION = 1
VALID_STATES = frozenset({"pending", "invalid", "running", "needs_review", "completed", "failed"})
REQUIRED_GATES = ("04_baseline_editor", "06_pointing_correction")
GATE_PASS_STATES = frozenset({"passed", "approved"})
_BATCH_ID = re.compile(r"[0-9a-f]{32}\Z")
_FITS_SUFFIXES = frozenset({".fits", ".fit"})
_MUTEX = threading.RLock()
_ACTIVE_WORKERS: dict[Path, threading.Lock] = {}


class BatchQueueError(ValueError):
    """Invalid observation selection or unsafe/invalid saved queue."""


class BatchConflict(BatchQueueError):
    """A concurrent change or stale revision prevented an update."""


def _now() -> str:
    """Return an unambiguous UTC timestamp for manifests and audit events."""
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _id(value: str) -> str:
    if not isinstance(value, str) or _BATCH_ID.fullmatch(value) is None:
        raise BatchQueueError("Invalid batch ID; expected a 32-character hexadecimal identifier.")
    return value


def _batches_dir(sessions_root: str | Path) -> Path:
    return Path(sessions_root) / "batches"


def _batch_path(sessions_root: str | Path, batch_id: str) -> Path:
    return _batches_dir(sessions_root) / f"{_id(batch_id)}.json"


def _validate_filename(name: Any, *, block: bool) -> str:
    """Require an unambiguous basename generated by File_check, not a path."""
    kind = "Block" if block else "FITS"
    if not isinstance(name, str) or not name or len(name) > 255:
        raise BatchQueueError(f"{kind} filename is missing or invalid.")
    if name in {".", ".."} or Path(name).name != name or "/" in name or "\\" in name or "\x00" in name:
        raise BatchQueueError(f"{kind} filename must be a single filename, not a directory path: {name!r}.")
    if block and not name.lower().endswith(".txt"):
        raise BatchQueueError(f"Block name is not a File_check .txt block: {name!r}.")
    if not block and Path(name).suffix.lower() not in _FITS_SUFFIXES:
        raise BatchQueueError(f"Unsupported FITS filename: {name!r}.")
    return name


def _as_path(value: Any, root: Path) -> Path:
    if not isinstance(value, str) or not value or "\x00" in value or len(value) > 4096:
        raise BatchQueueError("Selected FITS path must be a non-empty string.")
    raw = Path(value).expanduser()
    if not raw.is_absolute() and ".." in raw.parts:
        raise BatchQueueError(f"Relative FITS selection cannot contain '..': {value!r}.")
    path = (root / raw).resolve() if not raw.is_absolute() else raw.resolve()
    if not path.is_relative_to(root):
        raise BatchQueueError(f"Selected FITS path escapes the archive: {value!r}.")
    return path


def _selected_paths(selection: Mapping[str, Any]) -> dict[str, list[Path]]:
    """Resolve Page 01's selected_files, preserving ambiguous basename matches."""
    root_raw = selection.get("archive_root")
    if not isinstance(root_raw, str) or not root_raw.strip():
        raise BatchQueueError("Source selection is missing its committed FITS archive root.")
    archive_root = Path(root_raw).expanduser().resolve()
    selected = selection.get("selected_files")
    if not isinstance(selected, list) or not selected:
        raise BatchQueueError("Select and commit FITS files in Source Browser before preparing a batch.")
    absolute = selection.get("fits_file_paths")
    if absolute is not None and (not isinstance(absolute, list) or len(absolute) != len(selected)):
        raise BatchQueueError("Source selection has mismatched selected_files and fits_file_paths.")
    by_name: dict[str, list[Path]] = {}
    for index, value in enumerate(selected):
        path = _as_path(value, archive_root)
        if absolute is not None:
            expected = _as_path(absolute[index], archive_root)
            if path != expected:
                raise BatchQueueError(f"Source selection path mismatch for {value!r}; reselect the source.")
        _validate_filename(path.name, block=False)
        by_name.setdefault(path.name, []).append(path)
    return by_name


def _is_quarantined(path: Path) -> bool:
    # The standard folder name is supplied by fits_ingest and is "Flagged".
    # Checking all parents catches nested old quarantine directories too.
    return any(part.casefold() == "flagged" for part in path.parts)


def _verify_one(path: Path, verifier: Callable[[Path], Any] | None) -> list[str]:
    """Call the existing FR-03 structural verifier when provided; preserve its issues."""
    if verifier is None:
        return []
    try:
        result = verifier(path)
        if not bool(result.ok):
            return [f"FITS validation: {str(issue)[:600]}" for issue in result.issues] or [
                "FITS structural validation failed without an explanation."
            ]
        return []
    except Exception as exc:  # noqa: BLE001 — one corrupt file must not destroy another queue item
        return [f"FITS verification raised {type(exc).__name__}: {str(exc)[:600]}"]


def _file_issues(path: Path) -> tuple[list[str], dict[str, int] | None]:
    """Do read-only preflight checks and capture an identity for later revalidation."""
    if _is_quarantined(path):
        return ["The file is in a Flagged quarantine directory."], None
    try:
        if not path.is_file():
            return ["FITS file is missing or is not a regular file."], None
        stat = path.stat()
        if stat.st_size == 0:
            return ["FITS file is empty."], None
        with path.open("rb") as handle:
            handle.read(1)
        return [], {"size_bytes": stat.st_size, "mtime_ns": stat.st_mtime_ns}
    except OSError as exc:
        return [f"Cannot read FITS file: {exc}"], None


def _validated_blocks(selection: Mapping[str, Any], names: Sequence[str] | None) -> list[tuple[str, list[str]]]:
    blocks = selection.get("observation_blocks")
    if selection.get("file_check_error"):
        raise BatchQueueError("File_check failed; batch processing requires successful observation-block sorting.")
    if not isinstance(blocks, Mapping) or not blocks:
        raise BatchQueueError("No sorted observation blocks. Load/sort a source before preparing a batch.")
    for block_name, files in blocks.items():
        _validate_filename(block_name, block=True)
        if not isinstance(files, list) or any(not isinstance(item, str) for item in files):
            raise BatchQueueError(f"Block {block_name!r} must contain an ordered list of FITS filenames.")
    selected = list(blocks) if names is None else list(names)
    if not selected or len(selected) != len(set(selected)):
        raise BatchQueueError("Select one or more unique observation blocks.")
    if any(name not in blocks for name in selected):
        raise BatchQueueError("Selected block is not present in the committed Source Browser selection.")
    # Preserve the original File_check order, independent of multiselect click order.
    wanted = set(selected)
    return [(name, blocks[name]) for name in blocks if name in wanted]


def prepare_batch(
    selection: Mapping[str, Any], *, source_session_id: str, block_names: Sequence[str] | None = None,
    verifier: Callable[[Path], Any] | None = None,
) -> dict[str, Any]:
    """Validate every queued block against exact committed inputs and construct a manifest.

    Args:
        selection: Page 01's committed JSON-safe source stage payload.
        source_session_id: Reduction ID owning the File_check workspace.
        block_names: Optional subset of blocks; original sorting order is kept.
        verifier: Existing ``fits_ingest.verify_fits_file`` for full FR-03 checks,
            or None for fast metadata-only tests. No writes occur in either mode.

    Returns:
        A new, *unsaved* versioned batch manifest. Each bad block is INVALID
        with explicit reasons; other blocks remain PENDING and unprocessed.
    """
    if not isinstance(selection, Mapping):
        raise BatchQueueError("Source selection must be a saved mapping.")
    if not isinstance(source_session_id, str) or re.fullmatch(r"[A-Za-z0-9_-]{1,64}", source_session_id) is None:
        raise BatchQueueError("Invalid source reduction ID.")
    source = selection.get("source_name")
    frequency = selection.get("frequency_mhz")
    if not isinstance(source, str) or not source.strip():
        raise BatchQueueError("Source name is missing; reselect the source.")
    if isinstance(frequency, bool) or not isinstance(frequency, (int, float)) or not math.isfinite(frequency):
        raise BatchQueueError("Source frequency must be a finite MHz value.")
    if frequency <= 0:
        raise BatchQueueError("Source frequency must be greater than zero MHz.")
    blocks = _validated_blocks(selection, block_names)
    by_name = _selected_paths(selection)
    verified: dict[Path, list[str]] = {}
    occurrences = Counter(item for _, files in blocks for item in files)
    reused = {item for item, count in occurrences.items() if count > 1}
    jobs = []

    for block_name, files in blocks:
        issues: list[str] = []
        inputs = []
        if not files:
            issues.append("The sorted observation block contains no FITS files.")
        if len(set(files)) != len(files):
            issues.append("This observation block repeats a FITS filename.")
        for filename in files:
            try:
                _validate_filename(filename, block=False)
            except BatchQueueError as exc:
                issues.append(str(exc))
                continue
            candidates = by_name.get(filename, [])
            if len(candidates) != 1:
                description = "missing from the selection" if not candidates else "ambiguous in multiple directories"
                issues.append(f"{filename}: {description}.")
                continue
            path = candidates[0]
            current_issues, stamp = _file_issues(path)
            if not current_issues and path not in verified:
                verified[path] = _verify_one(path, verifier)
            current_issues.extend(verified.get(path, []))
            issues.extend(f"{filename}: {msg}" for msg in current_issues)
            inputs.append({"filename": filename, "path": str(path), "identity": stamp})
            if filename in reused:
                issues.append(f"{filename}: reused in multiple observation blocks; resolve this ambiguity first.")
        job_id = uuid.uuid4().hex
        jobs.append({
            "job_id": job_id,
            "block_name": block_name,
            "archive_root": str(Path(selection["archive_root"]).expanduser().resolve()),
            "inputs": inputs,
            "status": "invalid" if issues else "pending",
            "validation_issues": list(dict.fromkeys(issues)),
            "review": {"state": "not_requested", "stage": None, "reason": None, "approved_at": None},
            # Explicit per-block gates. Only the science worker may record an automatic pass
            # after validating that stage's scientific result; a questionable result is held
            # for a named operator rather than silently cleared.
            "gates": {stage: {"state": "pending", "evidence": None} for stage in REQUIRED_GATES},
            "session_id": None,
            "stage": None,
            "output_files": [],
            "error": None,
            "started_at": None,
            "finished_at": None,
        })
    if not jobs:
        raise BatchQueueError("No observation blocks were selected.")
    created = _now()
    return {
        "version": QUEUE_VERSION,
        "batch_id": uuid.uuid4().hex,
        "revision": 1,
        "created_at": created,
        "updated_at": created,
        "source_session_id": source_session_id,
        "source_name": source.strip(),
        "frequency_mhz": float(frequency),
        "template_session_id": None,
        "processing_enabled": False,  # Requires a validated reference-session pin before a worker starts
        "discarded_files": list(selection.get("discarded_files") or []),
        "jobs": jobs,
        "audit_log": [{"at": created, "action": "queue_prepared", "detail": f"{len(jobs)} block(s)"}],
    }


def revalidate_job_inputs(job: Mapping[str, Any]) -> list[str]:
    """Catch changed, removed or newly quarantined FITS files before every run."""
    problems = []
    archive = Path(job["archive_root"]).resolve() if job.get("archive_root") else None
    for item in job.get("inputs", []):
        path = Path(item["path"])
        if archive is not None and not path.resolve().is_relative_to(archive):
            problems.append(f"{item['filename']}: FITS path no longer resolves inside the archive.")
            continue
        errors, identity = _file_issues(path)
        if not errors and identity != item.get("identity"):
            errors.append("FITS input changed after the batch was prepared; requeue this block.")
        problems.extend(f"{item['filename']}: {message}" for message in errors)
    return problems


def _encode(document: Mapping[str, Any]) -> bytes:
    try:
        payload = json.dumps(document, sort_keys=True, allow_nan=False, indent=2).encode("utf-8")
    except (TypeError, ValueError) as exc:
        raise BatchQueueError(f"Batch manifest cannot be JSON-encoded: {exc}") from exc
    if len(payload) > MAX_MANIFEST_BYTES:
        raise BatchQueueError("Batch manifest exceeds the 4 MiB safety limit.")
    return payload


def _check_manifest(document: Any, batch_id: str) -> dict[str, Any]:
    """Reject malformed saved JSON before a later worker can trust its paths or job states."""
    if not isinstance(document, dict) or document.get("version") != QUEUE_VERSION:
        raise BatchQueueError("Unsupported or corrupt batch manifest format.")
    if document.get("batch_id") != batch_id or not isinstance(document.get("revision"), int):
        raise BatchQueueError("Batch ID or revision does not match the saved manifest.")
    if document["revision"] < 1 or not isinstance(document.get("jobs"), list) or not document["jobs"]:
        raise BatchQueueError("Batch revision or jobs list is invalid.")
    if not isinstance(document.get("processing_enabled"), bool):
        raise BatchQueueError("Batch processing-enabled field is invalid.")
    if not isinstance(document.get("audit_log"), list):
        raise BatchQueueError("Batch audit history is invalid.")
    if not isinstance(document.get("source_session_id"), str):
        raise BatchQueueError("Batch is missing the source reduction identity.")
    template = document.get("template")
    if template is not None:
        if (not isinstance(template, dict) or template.get("version") != 1
                or not isinstance(template.get("settings"), dict)
                or not isinstance(template.get("session_id"), str)
                or not isinstance(template.get("source_sha256"), str)
                or not re.fullmatch(r"[0-9a-f]{64}", template["source_sha256"])):
            raise BatchQueueError("Batch reference template snapshot is malformed.")
    seen_ids = set()
    for job in document["jobs"]:
        if not isinstance(job, dict) or job.get("status") not in VALID_STATES:
            raise BatchQueueError("Batch contains an invalid job status.")
        job_id = job.get("job_id")
        if not isinstance(job_id, str) or _BATCH_ID.fullmatch(job_id) is None or job_id in seen_ids:
            raise BatchQueueError("Batch contains a duplicate or invalid job identifier.")
        seen_ids.add(job_id)
        _validate_filename(job.get("block_name"), block=True)
        archive_root = job.get("archive_root")
        if archive_root is not None and (not isinstance(archive_root, str)
                                         or not Path(archive_root).is_absolute()):
            raise BatchQueueError("Job archive root must be an absolute path.")
        inputs, issues = job.get("inputs"), job.get("validation_issues")
        if not isinstance(inputs, list) or not isinstance(issues, list):
            raise BatchQueueError("Batch contains malformed job inputs or validation issues.")
        if any(not isinstance(issue, str) for issue in issues):
            raise BatchQueueError("Batch contains a non-textual validation issue.")
        if job["status"] == "invalid" and not issues:
            raise BatchQueueError("Invalid jobs must have at least one recorded validation issue.")
        if job["status"] != "invalid" and issues:
            raise BatchQueueError("A job with validation issues cannot be marked processable.")
        for item in inputs:
            if not isinstance(item, dict):
                raise BatchQueueError("Batch contains a malformed FITS input entry.")
            _validate_filename(item.get("filename"), block=False)
            raw_path = item.get("path")
            if not isinstance(raw_path, str) or not Path(raw_path).is_absolute() or "\x00" in raw_path:
                raise BatchQueueError("Batch FITS input path must be an absolute path.")
            if Path(raw_path).name != item["filename"]:
                raise BatchQueueError("The FITS input filename does not match its pinned path.")
            if archive_root is not None and not Path(raw_path).is_relative_to(Path(archive_root)):
                raise BatchQueueError("FITS input is outside the pinned archive directory.")
            identity = item.get("identity")
            if identity is not None and (not isinstance(identity, dict)
                                         or any(not isinstance(identity.get(k), int)
                                                or identity[k] < 0 for k in ("size_bytes", "mtime_ns"))):
                raise BatchQueueError("Batch FITS input snapshot is invalid.")
        if job["status"] != "invalid" and not inputs:
            raise BatchQueueError("A processable block cannot have an empty FITS input list.")
        assignment = job.get("pair_assignment")
        if assignment is not None:
            if not isinstance(assignment, dict):
                raise BatchQueueError("An expanded observation pair has invalid assignment metadata.")
            if (not isinstance(assignment.get("source_job_id"), str)
                    or _BATCH_ID.fullmatch(assignment["source_job_id"]) is None
                    or type(assignment.get("pair_number")) is not int
                    or type(assignment.get("pair_total")) is not int
                    or not 1 <= assignment["pair_number"] <= assignment["pair_total"]
                    or assignment.get("mode") not in {"Frequency Switch", "Position Switch"}
                    or not isinstance(assignment.get("scan_key"), str)
                    or not assignment["scan_key"]
                    or not isinstance(assignment.get("operator"), str)
                    or not assignment["operator"].strip()
                    or not isinstance(assignment.get("note"), str)
                    or not assignment["note"].strip()):
                raise BatchQueueError("An expanded pair lacks valid selection provenance.")
            pair_files, scan_files = assignment.get("pair_files"), assignment.get("scan_files")
            if (not isinstance(pair_files, list) or len(pair_files) != 2
                    or any(not isinstance(name, str) for name in pair_files)
                    or len(set(pair_files)) != 2 or not isinstance(scan_files, dict)
                    or set(scan_files) != {"N", "S", "E", "W", "Centre"}
                    or any(not isinstance(name, str) for name in scan_files.values())
                    or len(set(scan_files.values())) != 5):
                raise BatchQueueError("An expanded pair has invalid integration or pointing filenames.")
            reference = assignment.get("scan_reference")
            expected_names = set(pair_files) | set(scan_files.values()) | {reference}
            if (not isinstance(reference, str) or len(expected_names) != 8
                    or expected_names != {entry["filename"] for entry in inputs}):
                raise BatchQueueError("Expanded inputs must match exactly one pair and one complete scan.")
            for name in expected_names:
                _validate_filename(name, block=False)
        if not isinstance(job.get("review"), dict) or not isinstance(job.get("gates"), dict):
            raise BatchQueueError("Job review information is invalid.")
        review = job["review"]
        if review.get("state") not in {"not_requested", "requested", "approved"}:
            raise BatchQueueError("Job review state is invalid.")
        if review.get("signature") is not None and not re.fullmatch(
            r"[0-9a-f]{64}", str(review["signature"])
        ):
            raise BatchQueueError("Invalid signature for the held scientific result.")
        if review.get("approvable") is not None and not isinstance(review["approvable"], bool):
            raise BatchQueueError("Job approval policy must be boolean.")
        if review.get("details") is not None and not isinstance(review["details"], dict):
            raise BatchQueueError("Job review details must be a mapping.")
        if job.get("output_files") is not None and (not isinstance(job["output_files"], list)
                                                    or any(not isinstance(name, str) for name in job["output_files"])):
            raise BatchQueueError("Job output filenames are malformed.")
        for stage in REQUIRED_GATES:
            gate = job["gates"].get(stage)
            if not isinstance(gate, dict) or gate.get("state") not in {
                "pending", "requested", "passed", "approved",
            }:
                raise BatchQueueError(f"Job is missing a valid review gate for {stage}.")
            if job["status"] == "completed" and gate["state"] not in GATE_PASS_STATES:
                raise BatchQueueError(f"Completed block is missing required {stage} review approval.")
    return document


def _write_atomic(path: Path, payload: bytes, *, exclusive: bool) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".hartspec-batch-", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        if exclusive:
            os.link(temporary, path)  # Fail if the ID exists; no partial on-disk queue
        else:
            os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


@contextmanager
def _locked(path: Path):
    """Lock revision updates across threads (and POSIX workers on Ubuntu)."""
    with _MUTEX:
        lock_path = path.with_suffix(".lock")
        lock_path.parent.mkdir(parents=True, exist_ok=True)
        with lock_path.open("a+b") as stream:
            try:
                import fcntl  # POSIX deployment; Windows still has the process-local mutex
            except ImportError:
                fcntl = None
            if fcntl is not None:
                fcntl.flock(stream.fileno(), fcntl.LOCK_EX)
            try:
                yield
            finally:
                if fcntl is not None:
                    fcntl.flock(stream.fileno(), fcntl.LOCK_UN)


def create_batch(sessions_root: str | Path, manifest: Mapping[str, Any]) -> Path:
    """Persist a newly prepared queue; never overwrite previous queues."""
    batch_id = _id(manifest.get("batch_id"))
    _check_manifest(dict(manifest), batch_id)
    if manifest["revision"] != 1 or manifest["processing_enabled"]:
        raise BatchQueueError("Only prepared, non-running revision-one batches can be created.")
    path = _batch_path(sessions_root, batch_id)
    with _locked(path):
        try:
            _write_atomic(path, _encode(manifest), exclusive=True)
        except FileExistsError as exc:
            raise BatchConflict("This batch already exists; it was not overwritten.") from exc
    return path


def load_batch(sessions_root: str | Path, batch_id: str) -> dict[str, Any]:
    """Read a persisted batch without touching source sessions or FITS files."""
    path = _batch_path(sessions_root, batch_id)
    try:
        if path.stat().st_size > MAX_MANIFEST_BYTES:
            raise BatchQueueError("Batch manifest exceeds the 4 MiB safety limit.")

        def reject_constant(value: str) -> None:
            raise BatchQueueError(f"Non-finite number is not allowed in a batch: {value}.")

        document = json.loads(path.read_text(encoding="utf-8"), parse_constant=reject_constant)
        return _check_manifest(document, batch_id)
    except (OSError, json.JSONDecodeError) as exc:
        raise BatchQueueError(f"Cannot read batch {batch_id}: {exc}") from exc


def _update(sessions_root: str | Path, batch_id: str, expected_revision: int,
            apply: Callable[[dict[str, Any]], None]) -> dict[str, Any]:
    """Optimistically update an existing manifest without allowing lost updates."""
    path = _batch_path(sessions_root, batch_id)
    with _locked(path):
        document = load_batch(sessions_root, batch_id)
        if document["revision"] != expected_revision:
            raise BatchConflict("Batch was changed elsewhere. Reload its current state before continuing.")
        changed = copy.deepcopy(document)
        apply(changed)
        changed["revision"] += 1
        changed["updated_at"] = _now()
        _check_manifest(changed, batch_id)
        _write_atomic(path, _encode(changed), exclusive=False)
        return changed


def _job(document: dict[str, Any], job_id: str) -> dict[str, Any]:
    matches = [item for item in document["jobs"] if item["job_id"] == job_id]
    if len(matches) != 1:
        raise BatchQueueError("Unknown or duplicate batch job identifier.")
    return matches[0]


def update_job_status(
    sessions_root: str | Path, batch_id: str, job_id: str, status: str, *,
    expected_revision: int, reason: str = "", review_stage: str | None = None,
    review_signature: str | None = None, review_details: Mapping[str, Any] | None = None,
    approvable: bool = True, session_id: str | None = None,
    output_files: Sequence[str] | None = None, stage: str | None = None,
) -> dict[str, Any]:
    """Enforce safe queue transitions for the sequential scientific worker.

    A NEEDS_REVIEW job cannot advance until explicit scientific approval.
    Failed jobs can only restart through ``retry_job``; an operator can also
    skip a held block with ``skip_held_job`` to continue later observations.
    """
    transitions = {"pending": {"running"}, "running": {"needs_review", "failed", "completed"}}

    def apply(document: dict[str, Any]) -> None:
        if status == "running" and not document["processing_enabled"]:
            raise BatchQueueError("Processing is not connected yet; a prepared queue cannot start.")
        item = _job(document, job_id)
        old = item["status"]
        if status not in transitions.get(old, set()):
            raise BatchQueueError(f"Unsafe batch job transition: {old} → {status}.")
        if status == "running":
            if any(other["status"] == "running" and other["job_id"] != job_id
                   for other in document["jobs"]):
                raise BatchQueueError("Another observation block is already running; batch processing is sequential.")
            changed_inputs = revalidate_job_inputs(item)
            if changed_inputs:
                raise BatchQueueError("Cannot process modified FITS inputs: " + "; ".join(changed_inputs))
            if item["validation_issues"]:
                raise BatchQueueError("Cannot run a job with unresolved validation issues.")
            item["started_at"] = _now()
            item["finished_at"] = None
        if status in {"failed", "needs_review"} and not reason.strip():
            raise BatchQueueError("A failed or review-required job needs an explanation.")
        if status == "needs_review":
            if not review_stage:
                raise BatchQueueError("Review-required jobs must identify the pipeline stage.")
            if review_signature is not None and not re.fullmatch(r"[0-9a-f]{64}", review_signature):
                raise BatchQueueError("Review fingerprint must be 64 hexadecimal characters.")
            if review_details is not None and not isinstance(review_details, Mapping):
                raise BatchQueueError("Review scientific details must be a JSON-safe mapping.")
            item["review"] = {
                "state": "requested", "stage": review_stage, "reason": reason.strip(), "approved_at": None,
                "signature": review_signature, "details": dict(review_details or {}),
                "approvable": bool(approvable),
            }
            if review_stage in REQUIRED_GATES:
                item["gates"][review_stage] = {"state": "requested", "evidence": reason.strip()}
        if status == "completed":
            unresolved = [stage for stage in REQUIRED_GATES
                          if item["gates"].get(stage, {}).get("state") not in GATE_PASS_STATES]
            if unresolved:
                raise BatchQueueError("Cannot complete block with unresolved review gates: " + ", ".join(unresolved))
        if status == "failed":
            item["error"] = reason.strip()
        if stage is not None:
            if not isinstance(stage, str) or not re.fullmatch(r"[0-9]{2}_[a-z_]+", stage):
                raise BatchQueueError("Invalid last-stage key.")
            item["stage"] = stage
        if status == "completed":
            if not isinstance(session_id, str) or re.fullmatch(r"[A-Za-z0-9_-]{1,64}", session_id) is None:
                raise BatchQueueError("A completed block needs a saved, unique session identity.")
            if not output_files or any(name not in {"spectrum.csv", "spectrum.fits", "graphs.pdf", "session.json"}
                                       for name in output_files):
                raise BatchQueueError("A completed block needs its independently saved result files.")
            item["session_id"] = session_id
            item["output_files"] = list(output_files)
        if status in {"failed", "completed"}:
            item["finished_at"] = _now()
        item["status"] = status
        document["audit_log"].append({
            "at": _now(), "action": f"job_{status}", "job_id": job_id, "detail": reason.strip(),
        })

    return _update(sessions_root, batch_id, expected_revision, apply)


def approve_review(
    sessions_root: str | Path, batch_id: str, job_id: str, *,
    expected_revision: int, reviewer: str, note: str, justification: str = "",
) -> dict[str, Any]:
    """Record an actual person's approval; resume is a separate worker action."""
    if not reviewer.strip() or not note.strip():
        raise BatchQueueError("A named reviewer and an approval note are required.")

    def apply(document: dict[str, Any]) -> None:
        item = _job(document, job_id)
        if item["status"] != "needs_review" or item["review"].get("state") != "requested":
            raise BatchQueueError("Only a held job with a pending review request can be approved.")
        if item["review"].get("approvable") is False:
            raise BatchQueueError("This review needs corrected scientific inputs; approval cannot bypass it.")
        if (item["review"].get("stage") == "06_pointing_correction"
                and (item["review"].get("details") or {}).get("verdict") == "No-Go"
                and not justification.strip()):
            raise BatchQueueError("Pointing No-Go override needs a separate scientific justification.")
        item["review"] = {**item["review"], "state": "approved", "approved_at": _now(),
                          "reviewer": reviewer.strip(), "note": note.strip(),
                          "justification": justification.strip()}
        if item["review"]["stage"] in REQUIRED_GATES:
            item["gates"][item["review"]["stage"]] = {
                "state": "approved", "evidence": f"{reviewer.strip()}: {note.strip()}"
                + (f"; {justification.strip()}" if justification.strip() else ""),
                "signature": item["review"].get("signature"),
            }
        item["status"] = "pending"
        document["audit_log"].append({
            "at": _now(), "action": "review_approved", "job_id": job_id,
            "detail": f"{reviewer.strip()}: {note.strip()}"
            + (f"; scientific justification: {justification.strip()}" if justification.strip() else ""),
        })

    return _update(sessions_root, batch_id, expected_revision, apply)


def skip_held_job(
    sessions_root: str | Path, batch_id: str, job_id: str, *,
    expected_revision: int, operator: str, reason: str,
) -> dict[str, Any]:
    """Explicitly abandon an unapproved held block, preserving failed status and review evidence.

    Unlike approval, this action never bypasses a scientific check or produces
    a completed result. It lets later unrelated observation blocks proceed.
    """
    if not isinstance(operator, str) or not operator.strip() or not isinstance(reason, str) or not reason.strip():
        raise BatchQueueError("Skipping a held block requires an operator name and a reason.")

    def apply(document: dict[str, Any]) -> None:
        item = _job(document, job_id)
        if item["status"] != "needs_review" or item["review"].get("state") != "requested":
            raise BatchQueueError("Only an unapproved, review-held block can be skipped.")
        explanation = f"Skipped by {operator.strip()}: {reason.strip()}"
        item["status"] = "failed"
        item["error"] = explanation
        item["finished_at"] = _now()
        item["review"]["skipped_by"] = operator.strip()
        item["review"]["skip_reason"] = reason.strip()
        item["review"]["skipped_at"] = _now()
        document["audit_log"].append({
            "at": _now(), "action": "review_skipped", "job_id": job_id, "detail": explanation,
        })

    return _update(sessions_root, batch_id, expected_revision, apply)


def record_automatic_gate_pass(
    sessions_root: str | Path, batch_id: str, job_id: str, stage: str, *,
    expected_revision: int, evidence: str, signature: str | None = None,
) -> dict[str, Any]:
    """Worker-only audit point: record a scientifically checked, non-manual gate pass.

    The adapter must supply the real evaluated scientific evidence.
    We cannot infer a safe pointing outcome from a preflight FITS header.
    """
    if stage not in REQUIRED_GATES or not evidence.strip():
        raise BatchQueueError("Unknown review gate or missing scientific validation evidence.")

    def apply(document: dict[str, Any]) -> None:
        item = _job(document, job_id)
        if not document["processing_enabled"] or item["status"] != "running":
            raise BatchQueueError("Automatic gate passes may only be recorded during active processing.")
        if item["gates"][stage]["state"] == "requested":
            raise BatchQueueError("Operator review is required; an automatic pass would bypass the hold.")
        item["gates"][stage] = {"state": "passed", "evidence": evidence.strip(), "signature": signature}
        document["audit_log"].append({
            "at": _now(), "action": "automatic_gate_passed", "job_id": job_id,
            "detail": f"{stage}: {evidence.strip()}",
        })

    return _update(sessions_root, batch_id, expected_revision, apply)


def retry_job(sessions_root: str | Path, batch_id: str, job_id: str, *,
              expected_revision: int) -> dict[str, Any]:
    """Explicitly retry a failed job, requiring unchanged validated input files."""
    def apply(document: dict[str, Any]) -> None:
        item = _job(document, job_id)
        if item["status"] != "failed" or item["validation_issues"]:
            raise BatchQueueError("Only a failed job with valid inputs may be retried.")
        issues = revalidate_job_inputs(item)
        if issues:
            raise BatchQueueError("Cannot retry: " + "; ".join(issues))
        item["status"] = "pending"
        item["started_at"] = item["finished_at"] = None
        item["error"] = None
        document["audit_log"].append({"at": _now(), "action": "job_retried", "job_id": job_id, "detail": ""})
    return _update(sessions_root, batch_id, expected_revision, apply)


def batch_progress(manifest: Mapping[str, Any]) -> tuple[int, int]:
    """Return completed/total *blocks*, not files or pipeline stages."""
    jobs = manifest.get("jobs") or []
    return sum(job["status"] == "completed" for job in jobs), len(jobs)


def pin_batch_template(sessions_root: str | Path, batch_id: str, template: Mapping[str, Any], *,
                       expected_revision: int) -> dict[str, Any]:
    """Activate a prepared queue with a frozen, already validated manual session template.

    Science decisions (especially Page 06 acceptance) are never copied into
    the manifest, only the explicit settings enumerated by batch_template.
    """
    from utils.batch_template import signature

    snapshot = copy.deepcopy(dict(template))
    if not isinstance(snapshot.get("settings"), dict) or snapshot.get("version") != 1:
        raise BatchQueueError("Reference session must be validated before activation.")
    # Also ensures settings and the entire snapshot are valid JSON and finite.
    _encode(snapshot)
    identity = signature(snapshot)

    def apply(document: dict[str, Any]) -> None:
        if document["processing_enabled"] or any(job["status"] not in {"pending", "invalid"}
                                                 for job in document["jobs"]):
            raise BatchQueueError("Only an unstarted queue can pin a reference session.")
        document["template"] = snapshot
        document["template_session_id"] = snapshot["session_id"]
        document["template_signature"] = identity
        document["processing_enabled"] = True
        document["audit_log"].append({"at": _now(), "action": "reference_template_pinned",
                                      "detail": f"{snapshot['session_id']} sha256={identity}"})

    return _update(sessions_root, batch_id, expected_revision, apply)


@contextmanager
def worker_lock(sessions_root: str | Path, batch_id: str, job_id: str):
    """Prevent a second local/POSIX worker from running or recovering this job.

    The project deploys on Ubuntu, where fcntl protects across Streamlit
    processes. A process-local mutex provides a best-effort Windows test path.
    """
    lock_path = _batches_dir(sessions_root) / _id(batch_id) / "jobs" / _id(job_id) / ".worker.lock"
    with _MUTEX:
        mutex = _ACTIVE_WORKERS.setdefault(lock_path, threading.Lock())
    if not mutex.acquire(blocking=False):
        raise BatchConflict("The scientific worker is still active; wait before recovering this job.")
    try:
        lock_path.parent.mkdir(parents=True, exist_ok=True)
        with lock_path.open("a+b") as stream:
            try:
                import fcntl
            except ImportError:  # pragma: no cover - Windows development only
                fcntl = None
            if fcntl is not None:
                try:
                    fcntl.flock(stream.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
                except BlockingIOError as exc:
                    raise BatchConflict("The scientific worker is active in another server process.") from exc
            try:
                yield
            finally:
                if fcntl is not None:
                    fcntl.flock(stream.fileno(), fcntl.LOCK_UN)
    finally:
        mutex.release()


def mark_interrupted_job(sessions_root: str | Path, batch_id: str, job_id: str, *,
                         expected_revision: int, reason: str = "Worker interrupted") -> dict[str, Any]:
    """Conservatively release a stale RUNNING job as FAILED, never auto-complete it.

    Explicit operator action is required to resolve an interrupted job; a
    simultaneously active run must not be released while it still owns the
    queue. Only consider one stale after at least one hour with no updates.
    """
    def apply(document: dict[str, Any]) -> None:
        item = _job(document, job_id)
        if item["status"] != "running":
            raise BatchQueueError("Only a running job can be recovered as interrupted.")
        from datetime import timedelta
        started = datetime.fromisoformat(item["started_at"])
        if datetime.now(timezone.utc) - started < timedelta(hours=1):
            raise BatchQueueError("Running job may still be active; wait an hour before recovery.")
        item["status"] = "failed"
        item["error"] = reason
        item["finished_at"] = _now()
        document["audit_log"].append({"at": _now(), "action": "worker_interrupted",
                                      "job_id": job_id, "detail": reason})

    with worker_lock(sessions_root, batch_id, job_id):
        return _update(sessions_root, batch_id, expected_revision, apply)


def invalidate_changed_job(sessions_root: str | Path, batch_id: str, job_id: str, *,
                           expected_revision: int) -> dict[str, Any]:
    """Isolate a changed FITS file without preventing subsequent queued blocks."""
    def apply(document: dict[str, Any]) -> None:
        item = _job(document, job_id)
        if item["status"] != "pending":
            raise BatchQueueError("Only a pending observation can become invalid during preflight.")
        issues = revalidate_job_inputs(item)
        if not issues:
            raise BatchQueueError("FITS files are unchanged; no invalidation was performed.")
        item["validation_issues"] = issues
        item["status"] = "invalid"
        item["error"] = "Input changed after queue preparation. Prepare a new source selection to revalidate."
        item["finished_at"] = _now()
        document["audit_log"].append({"at": _now(), "action": "job_invalidated", "job_id": job_id,
                                      "detail": "; ".join(issues)[:2000]})

    return _update(sessions_root, batch_id, expected_revision, apply)
