@pytest.mark.parametrize("mode", ["light", "dark"])
@pytest.mark.parametrize("scale", [100, 200])
def test_streamlit_borders_preserve_all_other_computed_styles(page, monkeypatch, mode, scale):
    styles, ui = theme_module(monkeypatch, mode, scale)
    styles.inject_base_css()
    fragments = "".join(ui.fragments)
    dark = (APP / "utils/dark_surface_borders.css").read_text(encoding="utf-8")
    theme = styles.get_theme()
    # Page 05 and Page 08 rules are deliberately loaded LAST to verify specificity.
    later = (f'<style>[data-testid="stMain"] [data-testid="stVerticalBlockBorderWrapper"]'
             f'{{border-color:{theme["border-subtle"]} !important;}}'
             f'{export_page_ui.page_css(theme)}</style>')
    samples = []
    focused = []
    for css in (fragments.replace(dark, ""), fragments):
        page.set_content(NATIVE + css + later + MARKUP)
        samples.append({name: page.locator(f"#{name}").evaluate(SNAPSHOT) for name in SURFACES + PROTECTED})
        page.locator("#accessible").focus()
        focused.append(page.locator("#accessible").evaluate(SNAPSHOT)["outline"])
    old, new = samples
    assert focused[0] == focused[1]
    assert focused[1][0] == "2px"
    if mode == "light":
        assert old == new
    else:
        for name in SURFACES:
            assert new[name]["border"] == ["rgb(17, 24, 39)"] * 4, name
            assert {k: v for k, v in new[name].items() if k != "border"} == {
                k: v for k, v in old[name].items() if k != "border"
            }, name
        for name in PROTECTED:
            assert old[name] == new[name], name
    assert new["bare"]["width"] == "0px"
    assert new["export-parent"]["width"] == "0px"
    assert page.locator("#trace").get_attribute("stroke") == "#1F77B4"


@pytest.mark.parametrize("mode", ["light", "dark"])
@pytest.mark.parametrize("scale", [100, 200])
def test_dash_card_borders_only(page, monkeypatch, mode, scale):
    styles, _ = theme_module(monkeypatch, mode, scale)
    root = dash_style_functions(styles)["_root_style"](mode, scale)
    variables = ";".join(f"{key}:{value}" for key, value in root.items() if key.startswith("--"))
    css = (APP / "dash_apps/assets/baseline_editor.css").read_text(encoding="utf-8")
    html = f'''<div class="hs-dash-root" style="{variables}">
<h2 class="hs-panel-title" id="title">Baseline editor</h2>
<div class="hs-dash-panel" id="panel">Canvas</div><div class="hs-fit-cell" id="fit">Fit</div>
<div class="hs-controls-row" id="controls">Polynomial</div>
<div class="hs-block-panel"><div class="hs-controls-row hs-region-controls" id="bare"><label>Start
<input id="input" value="-12.4"/></label><button id="button">Add</button></div></div>
<div class="hs-keyboard-tools"><table><tr><th id="header">Sample</th></tr><tr><td id="cell">1</td></tr></table></div>
</div>'''
    samples = []
    for text in (css.replace("var(--hs-surface-border, var(--hs-border-default))", "var(--hs-border-default)"), css):
        page.set_content(f'<style>html{{font-size:{16 * scale / 100}px;}}{text}</style>' + html)
        samples.append({name: page.locator(f"#{name}").evaluate(SNAPSHOT)
                        for name in ("title", "panel", "fit", "controls", "bare", "input", "button", "header", "cell")})
    old, new = samples
    if mode == "light":
        assert old == new
    else:
        for name in ("panel", "fit", "controls"):
            assert new[name]["border"] == ["rgb(17, 24, 39)"] * 4
            assert {k: v for k, v in old[name].items() if k != "border"} == {
                k: v for k, v in new[name].items() if k != "border"
            }
        for name in ("title", "bare", "input", "button", "header", "cell"):
            assert new[name] == old[name]
    assert new["bare"]["width"] == "0px"


@pytest.mark.parametrize("mode", ["light", "dark"])
@pytest.mark.parametrize("scale", [100, 200])
def test_embedded_header_table_preserves_fills_and_focus(page, monkeypatch, mode, scale):
    styles, _ = theme_module(monkeypatch, mode, scale)
    theme = styles.get_theme()
    rendered = header_html(styles, pd.DataFrame({"Value": [1.23456789, 2.0]}, index=["one", "two"]))
    page.set_content(rendered)
    wrap = page.locator(".wrap")
    expected = "rgb(17, 24, 39)" if mode == "dark" else "rgb(226, 232, 240)"
    assert wrap.evaluate(SNAPSHOT)["border"] == [expected] * 4
    assert wrap.evaluate(SNAPSHOT)["width"] == "1px"
    assert wrap.evaluate("e => getComputedStyle(e).backgroundColor") == (
        "rgb(30, 41, 59)" if mode == "dark" else "rgb(255, 255, 255)"
    )
    wrap.focus()
    assert wrap.evaluate("e => getComputedStyle(e).outlineWidth") == "3px"
    assert "1.23456789" in wrap.inner_text()
    assert theme["bg-panel"] != theme["table-header-bg"]
